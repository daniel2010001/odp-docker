#!/usr/bin/env bash
#
# Guards the production stack against a volume over Python's site-packages.
#
# Run from anywhere:  bash tests/test-prod-site-packages.sh
#
# `ckanext-umss` and CKAN itself are installed into the image's
# `/usr/local/lib/python3.14/site-packages`. Docker fills a named volume from the
# image only when it creates the volume, so a named volume mounted there keeps the
# code of the FIRST image forever: every later `up --build` serves the old code
# with no error. Measured on 2026-10-20: the hs-node demo's image carried
# migration 0002 while its `site_packages_py314` volume still held only 0001.
#
# What is enforced, on Compose's own resolved config (`config --format json`), for
# the prod compose alone and for the hs-node demo (unified + `docker-compose.hs.yml`):
#
#   1. No service mounts anything at or under a `site-packages` directory.
#   2. No top-level volume is named `site_packages*`.
#
# The dev stack (`ckan-docker/docker-compose.dev.yml`) keeps its volume on
# purpose: it installs the extensions editable from a bind mount. Not checked here.
#
# Every run uses a scratch copy with fake env values: the real `.env` files are
# never read. `config` needs the Compose CLI but no daemon.
#
# No `set -e`: the harness decides what a non-zero status means.

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$HERE/.." && pwd)"

failures=0
pass() { printf 'ok   %s\n' "$1"; }
fail() { printf 'FAIL %s\n' "$1"; failures=$((failures + 1)); }
finish() {
	if [[ "$failures" -ne 0 ]]; then
		printf '\n%d check(s) failed\n' "$failures"
		exit 1
	fi
	printf '\nall checks passed\n'
	exit 0
}

if ! docker compose version >/dev/null 2>&1; then
	fail "the docker compose CLI is required (no daemon needed)"
	finish
fi
if ! command -v jq >/dev/null 2>&1; then
	fail "jq is required"
	finish
fi

S="$(mktemp -d)"
trap 'rm -rf "$S"' EXIT
mkdir -p "$S/ckan-docker"
cp "$REPO_ROOT/docker-compose.unified.yml" "$REPO_ROOT/docker-compose.hs.yml" "$S/"
cp "$REPO_ROOT/ckan-docker/docker-compose.yml" "$S/ckan-docker/"
cp "$REPO_ROOT/ckan-docker/.env.example" "$S/ckan-docker/.env"
printf 'SESSION_SECRET=fake\n' >"$S/.env"
# Every empty key of the demo example filled with a fake value.
awk -F= '/^[A-Z_][A-Z0-9_]*=/ && $2 == "" { print $1 "=fake-" $1; next } { print }' \
	"$REPO_ROOT/demo.env.example" >"$S/.env.demo"

compose() { (cd "$S" && DOCKER_HOST=unix:///nonexistent docker compose "$@"); }

check() {
	local label="$1" json="$2" mounts names
	mounts="$(jq -r '.services | to_entries[] | .key as $s | (.value.volumes // [])[]
		| select(.target | test("site-packages")) | "\($s): \(.source // "-") -> \(.target)"' "$json")"
	if [[ -z "$mounts" ]]; then
		pass "$label: no service mounts a volume over site-packages"
	else
		fail "$label: a volume hides the image's site-packages: $(tr '\n' ';' <<<"$mounts")"
	fi
	names="$(jq -r '(.volumes // {}) | keys[] | select(test("site_packages"))' "$json")"
	if [[ -z "$names" ]]; then
		pass "$label: declares no site_packages volume"
	else
		fail "$label: declares $(tr '\n' ' ' <<<"$names")"
	fi
}

if compose -f ckan-docker/docker-compose.yml config --format json >"$S/prod.json" 2>"$S/prod.err"; then
	check "prod compose" "$S/prod.json"
else
	fail "prod compose: config exits non-zero: $(head -c 400 "$S/prod.err")"
fi

if compose -f docker-compose.unified.yml -f docker-compose.hs.yml --env-file .env.demo \
	config --format json >"$S/demo.json" 2>"$S/demo.err"; then
	check "hs-node demo" "$S/demo.json"
	# The other persistent volumes are untouched: data must survive a rebuild.
	for v in ckan_storage pg_data solr_data; do
		if jq -e --arg v "$v" '(.volumes // {}) | has($v)' "$S/demo.json" >/dev/null; then
			pass "hs-node demo: still declares $v"
		else
			fail "hs-node demo: lost the $v volume"
		fi
	done
else
	fail "hs-node demo: config exits non-zero: $(head -c 400 "$S/demo.err")"
fi

finish
